-- Ekhaya Commerce Platform: initial multi-tenant core schema
-- Target: Supabase/PostgreSQL. Apply only to the new platform database.
-- Tenant isolation is enforced through store membership RLS policies.

create extension if not exists pgcrypto;

create type public.store_status as enum ('draft', 'active', 'suspended');
create type public.member_role as enum ('owner', 'admin', 'staff');
create type public.product_status as enum ('draft', 'active', 'archived');
create type public.order_status as enum (
  'pending', 'paid', 'processing', 'shipped', 'completed', 'cancelled', 'refunded'
);

create table public.stores (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  status public.store_status not null default 'draft',
  currency char(3) not null default 'ZAR',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.store_memberships (
  store_id uuid not null references public.stores(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.member_role not null default 'staff',
  created_at timestamptz not null default now(),
  primary key (store_id, user_id)
);

create table public.store_domains (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  hostname text not null unique,
  is_primary boolean not null default false,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  constraint hostname_lowercase check (hostname = lower(hostname))
);

create unique index store_domains_one_primary_per_store
  on public.store_domains(store_id) where is_primary = true;

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  name text not null,
  slug text not null,
  created_at timestamptz not null default now(),
  unique (store_id, slug),
  unique (store_id, id)
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  category_id uuid,
  name text not null,
  slug text not null,
  description text not null default '',
  sku text,
  price numeric(12,2) not null check (price >= 0),
  compare_at_price numeric(12,2) check (compare_at_price is null or compare_at_price >= 0),
  inventory_quantity integer not null default 0 check (inventory_quantity >= 0),
  status public.product_status not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, slug),
  unique (store_id, sku),
  foreign key (store_id, category_id) references public.categories(store_id, id)
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  email text not null,
  first_name text,
  last_name text,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, email),
  unique (store_id, id)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  customer_id uuid,
  order_number bigint generated by default as identity,
  status public.order_status not null default 'pending',
  currency char(3) not null default 'ZAR',
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  shipping_total numeric(12,2) not null default 0 check (shipping_total >= 0),
  tax_total numeric(12,2) not null default 0 check (tax_total >= 0),
  discount_total numeric(12,2) not null default 0 check (discount_total >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  customer_email text not null,
  shipping_address jsonb not null default '{}'::jsonb,
  billing_address jsonb not null default '{}'::jsonb,
  payment_provider text,
  payment_reference text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, order_number),
  foreign key (store_id, customer_id) references public.customers(store_id, id)
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  order_id uuid not null,
  product_id uuid,
  product_name text not null,
  sku text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  created_at timestamptz not null default now(),
  foreign key (store_id, order_id) references public.orders(store_id, id) on delete cascade,
  foreign key (store_id, product_id) references public.products(store_id, id)
);

create index products_store_status_idx on public.products(store_id, status);
create index orders_store_created_idx on public.orders(store_id, created_at desc);
create index orders_store_customer_idx on public.orders(store_id, customer_id);
create index order_items_store_order_idx on public.order_items(store_id, order_id);

create function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger stores_set_updated_at before update on public.stores
  for each row execute function public.set_updated_at();
create trigger products_set_updated_at before update on public.products
  for each row execute function public.set_updated_at();
create trigger customers_set_updated_at before update on public.customers
  for each row execute function public.set_updated_at();
create trigger orders_set_updated_at before update on public.orders
  for each row execute function public.set_updated_at();

-- Helper is SECURITY DEFINER to avoid recursive membership-policy evaluation.
create function public.is_store_member(target_store_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.store_memberships sm
    where sm.store_id = target_store_id
      and sm.user_id = (select auth.uid())
  );
$$;

create function public.has_store_role(target_store_id uuid, allowed_roles public.member_role[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.store_memberships sm
    where sm.store_id = target_store_id
      and sm.user_id = (select auth.uid())
      and sm.role = any(allowed_roles)
  );
$$;

alter table public.stores enable row level security;
alter table public.store_memberships enable row level security;
alter table public.store_domains enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.customers enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "members can read their stores" on public.stores
  for select to authenticated using (public.is_store_member(id));
create policy "authenticated users can create stores" on public.stores
  for insert to authenticated with check (true);
create policy "store admins can update stores" on public.stores
  for update to authenticated using (public.has_store_role(id, array['owner','admin']::public.member_role[]))
  with check (public.has_store_role(id, array['owner','admin']::public.member_role[]));

create policy "members can read memberships" on public.store_memberships
  for select to authenticated using (public.is_store_member(store_id));
create policy "owners and admins manage memberships" on public.store_memberships
  for all to authenticated
  using (public.has_store_role(store_id, array['owner','admin']::public.member_role[]))
  with check (public.has_store_role(store_id, array['owner','admin']::public.member_role[]));

create policy "members manage store domains" on public.store_domains
  for all to authenticated
  using (public.has_store_role(store_id, array['owner','admin']::public.member_role[]))
  with check (public.has_store_role(store_id, array['owner','admin']::public.member_role[]));

create policy "members manage categories" on public.categories
  for all to authenticated using (public.is_store_member(store_id))
  with check (public.is_store_member(store_id));
create policy "members manage products" on public.products
  for all to authenticated using (public.is_store_member(store_id))
  with check (public.is_store_member(store_id));
create policy "members manage customers" on public.customers
  for all to authenticated using (public.is_store_member(store_id))
  with check (public.is_store_member(store_id));
create policy "members manage orders" on public.orders
  for all to authenticated using (public.is_store_member(store_id))
  with check (public.is_store_member(store_id));
create policy "members manage order items" on public.order_items
  for all to authenticated using (public.is_store_member(store_id))
  with check (public.is_store_member(store_id));

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.stores, public.store_memberships,
  public.store_domains, public.categories, public.products, public.customers,
  public.orders, public.order_items to authenticated;
grant execute on function public.is_store_member(uuid) to authenticated;
grant execute on function public.has_store_role(uuid, public.member_role[]) to authenticated;
